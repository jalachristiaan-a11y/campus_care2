require('dotenv').config();

const db = require('../config/db.cjs');

const initializeDatabase = async () => {
  const client = await db.connect();

  try {
    await client.query('BEGIN');
    await client.query(`
      CREATE TABLE IF NOT EXISTS departments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL UNIQUE,
        email VARCHAR(150) NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS users (
        id VARCHAR(20) PRIMARY KEY,
        full_name VARCHAR(100) NOT NULL,
        email VARCHAR(100) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        role VARCHAR(20) NOT NULL,
        department_id INTEGER REFERENCES departments(id),
        is_submission_blocked BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS complaints (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        public_id VARCHAR(40) NOT NULL UNIQUE,
        user_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        submitted_by VARCHAR(100) NOT NULL,
        submitted_by_name VARCHAR(100) NOT NULL,
        student_id VARCHAR(20) NOT NULL,
        category VARCHAR(60) NOT NULL,
        title VARCHAR(120) NOT NULL,
        description VARCHAR(3000) NOT NULL,
        location VARCHAR(120) NOT NULL DEFAULT '',
        attachment JSONB,
        status VARCHAR(20) NOT NULL DEFAULT 'Under Review'
          CHECK (status IN ('Under Review', 'In Progress', 'Resolved')),
        department VARCHAR(100) NOT NULL DEFAULT 'Awaiting assignment',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      ALTER TABLE complaints
      DROP CONSTRAINT IF EXISTS complaints_status_check
    `);
    await client.query(`
      ALTER TABLE complaints
      ADD CONSTRAINT complaints_status_check
      CHECK (status IN ('Under Review', 'In Progress', 'Resolved', 'Withdrawn'))
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS complaints_user_created_idx
      ON complaints (user_id, created_at DESC)
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS complaints_created_idx
      ON complaints (created_at DESC)
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS complaint_activity (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        complaint_id BIGINT NOT NULL REFERENCES complaints(id) ON DELETE CASCADE,
        actor_user_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        actor_role VARCHAR(20) NOT NULL,
        event_type VARCHAR(30) NOT NULL,
        message VARCHAR(3000) NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS complaint_activity_complaint_created_idx
      ON complaint_activity (complaint_id, created_at, id)
    `);
    await client.query(`
      INSERT INTO complaint_activity
        (complaint_id, actor_user_id, actor_role, event_type, message, created_at)
      SELECT c.id, c.user_id, 'student', 'submitted', 'Complaint submitted.', c.created_at
      FROM complaints c
      WHERE NOT EXISTS (
        SELECT 1
        FROM complaint_activity a
        WHERE a.complaint_id = c.id
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS student_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sender_user_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        recipient_user_id VARCHAR(20) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        subject VARCHAR(200) NOT NULL,
        message TEXT NOT NULL,
        type VARCHAR(60) NOT NULL DEFAULT 'Official Notice',
        sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS system_settings (
        setting_key VARCHAR(50) PRIMARY KEY,
        value JSONB NOT NULL,
        updated_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      INSERT INTO system_settings (setting_key, value)
      VALUES ('portal', '{"intakeOpen": true, "slaHours": 48, "urgentSlaHours": 12}'::jsonb)
      ON CONFLICT (setting_key) DO NOTHING
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS student_messages_recipient_sent_idx
      ON student_messages (recipient_user_id, sent_at DESC)
    `);
    await client.query('COMMIT');
    console.log('Database initialized: users, departments, complaints, student messages, and system settings are ready.');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
    await db.end();
  }
};

initializeDatabase().catch((error) => {
  console.error('Database initialization failed:', error.message);
  process.exitCode = 1;
});
