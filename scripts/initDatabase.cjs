require('dotenv').config();

const db = require('../config/db.cjs');

const initializeDatabase = async () => {
  const client = await db.connect();

  try {
    await client.query('BEGIN');
    await client.query(`
      CREATE TABLE IF NOT EXISTS departments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL UNIQUE,
        email VARCHAR(150) NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS users (
        id VARCHAR(20) PRIMARY KEY,
        full_name VARCHAR(100) NOT NULL,
        email VARCHAR(100) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        role VARCHAR(20) NOT NULL,
        department_id INTEGER REFERENCES departments(id),
        is_submission_blocked BOOLEAN NOT NULL DEFAULT FALSE,
        email_verified_at TIMESTAMPTZ,
        cor_status VARCHAR(20) NOT NULL DEFAULT 'pending',
        email_verification_send_count SMALLINT NOT NULL DEFAULT 0,
        email_verification_send_window_started_at TIMESTAMPTZ,
        email_verification_last_sent_at TIMESTAMPTZ,
        cor_document JSONB,
        cor_submitted_at TIMESTAMPTZ,
        cor_reviewed_at TIMESTAMPTZ,
        cor_reviewed_by VARCHAR(20) REFERENCES users(id),
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      ALTER TABLE users
      ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS cor_status VARCHAR(20) NOT NULL DEFAULT 'pending',
      ADD COLUMN IF NOT EXISTS email_verification_send_count SMALLINT NOT NULL DEFAULT 0,
      ADD COLUMN IF NOT EXISTS email_verification_send_window_started_at TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS email_verification_last_sent_at TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS cor_document JSONB,
      ADD COLUMN IF NOT EXISTS cor_submitted_at TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS cor_reviewed_at TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS cor_reviewed_by VARCHAR(20)
    `);
    await client.query(`
      DO $$
      BEGIN
        IF NOT EXISTS (
          SELECT 1 FROM pg_constraint
          WHERE conname = 'users_cor_status_check'
            AND conrelid = 'users'::regclass
        ) THEN
          ALTER TABLE users
          ADD CONSTRAINT users_cor_status_check
          CHECK (cor_status IN ('pending', 'approved', 'rejected'));
        END IF;
      END $$;
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS email_verification_codes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id VARCHAR(20) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        code_hash CHAR(64) NOT NULL,
        expires_at TIMESTAMPTZ NOT NULL,
        failed_attempts SMALLINT NOT NULL DEFAULT 0,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      ALTER TABLE email_verification_codes
      ADD COLUMN IF NOT EXISTS failed_attempts SMALLINT NOT NULL DEFAULT 0
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS user_sessions (
        token_hash CHAR(64) PRIMARY KEY,
        user_id VARCHAR(20) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires_at TIMESTAMPTZ NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS user_sessions_expires_at_idx
      ON user_sessions (expires_at)
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS complaints (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        public_id VARCHAR(40) NOT NULL UNIQUE,
        user_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        submitted_by VARCHAR(100) NOT NULL,
        submitted_by_name VARCHAR(100) NOT NULL,
        student_id VARCHAR(20) NOT NULL,
        category VARCHAR(60) NOT NULL,
        title VARCHAR(120) NOT NULL,
        description VARCHAR(3000) NOT NULL,
        location VARCHAR(120) NOT NULL DEFAULT '',
        attachment JSONB,
        urgency SMALLINT NOT NULL DEFAULT 1,
        assigned_admin_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        assigned_at TIMESTAMPTZ,
        status VARCHAR(32) NOT NULL DEFAULT 'Submitted'
          CHECK (status IN ('Submitted', 'Under Review', 'In Progress', 'Resolved')),
        department VARCHAR(100) NOT NULL DEFAULT 'Awaiting assignment',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      ALTER TABLE complaints
      ADD COLUMN IF NOT EXISTS urgency SMALLINT NOT NULL DEFAULT 1,
      ADD COLUMN IF NOT EXISTS assigned_admin_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
      ADD COLUMN IF NOT EXISTS assigned_at TIMESTAMPTZ
    `);
    await client.query(`
      DO $$
      BEGIN
        IF NOT EXISTS (
          SELECT 1 FROM pg_constraint
          WHERE conname = 'complaints_urgency_check'
            AND conrelid = 'complaints'::regclass
        ) THEN
          ALTER TABLE complaints
          ADD CONSTRAINT complaints_urgency_check
          CHECK (urgency BETWEEN 1 AND 4);
        END IF;
      END $$;
    `);
    const complaintShape = await client.query(`
      SELECT column_name
      FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'complaints'
    `);
    const complaintColumns = new Set(complaintShape.rows.map((row) => row.column_name));
    const requiredComplaintColumns = [
      'public_id',
      'user_id',
      'submitted_by',
      'submitted_by_name',
      'student_id',
      'category',
      'title',
      'description',
      'location',
      'attachment',
      'assigned_admin_id',
      'status',
      'department',
    ];
    const missingComplaintColumns = requiredComplaintColumns.filter((column) => !complaintColumns.has(column));
    if (missingComplaintColumns.length > 0) {
      throw new Error(
        `The existing complaints table uses an incompatible legacy schema. Missing: ${missingComplaintColumns.join(', ')}. ` +
        'Create a fresh CampusCare database and run npm run db:init instead of importing the older dump into this database.'
      );
    }
    await client.query(`
      ALTER TABLE complaints
      ALTER COLUMN status TYPE VARCHAR(32)
    `);
    await client.query(`
      DO $$
      DECLARE
        status_constraint RECORD;
      BEGIN
        FOR status_constraint IN
          SELECT conname
          FROM pg_constraint
          WHERE conrelid = 'public.complaints'::regclass
            AND contype = 'c'
            AND pg_get_constraintdef(oid) ILIKE '%status%'
        LOOP
          EXECUTE format('ALTER TABLE complaints DROP CONSTRAINT %I', status_constraint.conname);
        END LOOP;
      END $$;
    `);
    await client.query(`
      UPDATE complaints
      SET status = CASE
        WHEN assigned_admin_id IS NULL THEN 'Submitted'
        ELSE 'Under Review'
      END
      WHERE status IN ('Waiting for Review', 'submitted', 'under_review')
         OR (status = 'Under Review' AND assigned_admin_id IS NULL)
    `);
    await client.query(`
      ALTER TABLE complaints
      ALTER COLUMN status SET DEFAULT 'Submitted'
    `);
    await client.query(`
      ALTER TABLE complaints
      ADD CONSTRAINT complaints_status_check
      CHECK (status IN (
        'Submitted',
        'Under Review',
        'Need More Information',
        'In Progress',
        'Resolved',
        'Rejected',
        'Withdrawn',
        'Closed'
      ))
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS complaints_user_created_idx
      ON complaints (user_id, created_at DESC)
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS complaints_created_idx
      ON complaints (created_at DESC)
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS complaints_assigned_admin_idx
      ON complaints (assigned_admin_id)
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS complaint_activity (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        complaint_id BIGINT NOT NULL REFERENCES complaints(id) ON DELETE CASCADE,
        actor_user_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        actor_role VARCHAR(20) NOT NULL,
        event_type VARCHAR(30) NOT NULL,
        message VARCHAR(3000) NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS complaint_activity_complaint_created_idx
      ON complaint_activity (complaint_id, created_at, id)
    `);
    await client.query(`
      INSERT INTO complaint_activity
        (complaint_id, actor_user_id, actor_role, event_type, message, created_at)
      SELECT c.id, c.user_id, 'student', 'submitted', 'Complaint submitted.', c.created_at
      FROM complaints c
      WHERE NOT EXISTS (
        SELECT 1
        FROM complaint_activity a
        WHERE a.complaint_id = c.id
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS student_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sender_user_id VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        recipient_user_id VARCHAR(20) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        subject VARCHAR(200) NOT NULL,
        message TEXT NOT NULL,
        type VARCHAR(60) NOT NULL DEFAULT 'Official Notice',
        sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS system_settings (
        setting_key VARCHAR(50) PRIMARY KEY,
        value JSONB NOT NULL,
        updated_by VARCHAR(20) REFERENCES users(id) ON DELETE SET NULL,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await client.query(`
      INSERT INTO system_settings (setting_key, value)
      VALUES ('portal', '{"intakeOpen": true, "slaHours": 48, "urgentSlaHours": 12}'::jsonb)
      ON CONFLICT (setting_key) DO NOTHING
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS student_messages_recipient_sent_idx
      ON student_messages (recipient_user_id, sent_at DESC)
    `);
    await client.query('COMMIT');
    console.log('Database initialized: users, sessions, departments, complaints, student messages, and system settings are ready.');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
    await db.end();
  }
};

initializeDatabase().catch((error) => {
  console.error('Database initialization failed:', error.message);
  process.exitCode = 1;
});
